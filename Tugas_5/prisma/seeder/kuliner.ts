async function main() {
  for (const item of dataKuliner) {
    await prisma.kuliner.upsert({
      where: { id: item.id },
      update: { gambar: item.gambar, sejarah: item.sejarah },
      create: { ...item },
    });
  }
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (e) => {
    console.error(e);
    await prisma.$disconnect();
    process.exit(1);
  });